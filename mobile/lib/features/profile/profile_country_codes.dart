bool isProfileCountry(String name) =>
    _countryCodes.containsKey(name.toLowerCase()) ||
    _countryCodes.containsValue(name.toUpperCase());

String compactProfileCity(String location) {
  final comma = location.lastIndexOf(',');
  if (comma < 1) return location;
  final country = location.substring(comma + 1).trim();
  final code = _countryCodes[country.toLowerCase()];
  if (code == null) return location;
  return '${location.substring(0, comma).trimRight()}, $code';
}
