//! Live huddle video transport, authorization, and ephemeral storage witnesses.
//!
//! Run against a local relay built from this branch:
//! `cargo test -p buzz-test-client --test e2e_huddle_screen -- --ignored`.

use std::time::Duration;

use anyhow::{bail, Context, Result};
use buzz_core::{
    huddle_screen::{ScreenMessage, ScreenShare},
    kind::{
        KIND_HUDDLE_SCREEN, KIND_NIP29_CREATE_GROUP, KIND_NIP29_EDIT_METADATA, KIND_NIP29_PUT_USER,
    },
};
use buzz_test_client::{BuzzTestClient, RelayMessage};
use nostr::{Alphabet, Event, EventBuilder, Filter, Keys, Kind, SingleLetterTag, Tag};
use sqlx::postgres::PgPoolOptions;
use uuid::Uuid;

const DEADLINE: Duration = Duration::from_secs(5);

struct Room {
    url: String,
    other_url: String,
    channel: String,
    owner: Keys,
    viewer: Keys,
    outsider: Keys,
    publisher: BuzzTestClient,
    pool: sqlx::PgPool,
    community: Uuid,
}

fn filter(channel: &str) -> Filter {
    Filter::new()
        .kind(Kind::Custom(KIND_HUDDLE_SCREEN as u16))
        .custom_tags(SingleLetterTag::lowercase(Alphabet::H), [channel])
        .limit(0)
}

fn sign(keys: &Keys, kind: u32, content: String, tags: Vec<Tag>) -> Result<Event> {
    Ok(EventBuilder::new(Kind::Custom(kind as u16), content)
        .tags(tags)
        .sign_with_keys(keys)?)
}

fn video_packets() -> Result<Vec<ScreenMessage>> {
    // This fixture is generated by the production native OpenH264 encoder.
    let mut packets: Vec<ScreenMessage> = serde_json::from_str(include_str!(
        "../../../desktop/tests/fixtures/huddle-video.json"
    ))?;
    let share = ScreenShare {
        session_id: Uuid::new_v4(),
        started_at: nostr::Timestamp::now().as_secs() * 1000,
        label: "Live relay screen test".into(),
    };
    for packet in &mut packets {
        match packet {
            ScreenMessage::Video { share: current, .. }
            | ScreenMessage::Stopped { share: current } => *current = share.clone(),
        }
    }
    Ok(packets)
}

fn screen_event(keys: &Keys, message: &ScreenMessage, channels: &[&str]) -> Result<Event> {
    sign(
        keys,
        KIND_HUDDLE_SCREEN,
        serde_json::to_string(message)?,
        channels
            .iter()
            .map(|channel| Tag::parse(["h", *channel]))
            .collect::<std::result::Result<_, _>>()?,
    )
}

async fn accepted(client: &mut BuzzTestClient, event: Event) -> Result<()> {
    let response = client.send_event(event).await?;
    assert!(
        response.accepted,
        "relay rejected event: {}",
        response.message
    );
    Ok(())
}

async fn room() -> Result<Room> {
    let url = std::env::var("RELAY_URL").unwrap_or_else(|_| "ws://localhost:3000".into());
    let mut parsed = url::Url::parse(&url)?;
    let host = match parsed.host_str() {
        Some("localhost") => "127.0.0.1",
        Some("127.0.0.1") => "localhost",
        _ => bail!("This isolated-tenant test requires a local loopback relay"),
    };
    let authority = parsed[url::Position::BeforeHost..url::Position::AfterPort].to_owned();
    parsed.set_host(Some(host))?;
    let other_authority = parsed[url::Position::BeforeHost..url::Position::AfterPort].to_owned();
    let other_url = parsed.to_string();
    let database = std::env::var("DATABASE_URL")
        .unwrap_or_else(|_| "postgres://buzz:buzz_dev@localhost:5432/buzz".into());
    let pool = PgPoolOptions::new()
        .max_connections(1)
        .connect(&database)
        .await?;
    let owner = Keys::generate();
    let viewer = Keys::generate();
    let outsider = Keys::generate();
    for host in [&authority, &other_authority] {
        sqlx::query(
            "INSERT INTO communities (host) VALUES ($1) ON CONFLICT (lower(host)) DO NOTHING",
        )
        .bind(host)
        .execute(&pool)
        .await?;
        let community: Uuid =
            sqlx::query_scalar("SELECT id FROM communities WHERE lower(host) = lower($1)")
                .bind(host)
                .fetch_one(&pool)
                .await?;
        for (keys, role) in [
            (&owner, "owner"),
            (&viewer, "member"),
            (&outsider, "member"),
        ] {
            sqlx::query(
                "INSERT INTO relay_members (community_id, pubkey, role, added_by) \
                 VALUES ($1, $2, $3, NULL)",
            )
            .bind(community)
            .bind(keys.public_key().to_hex())
            .bind(role)
            .execute(&pool)
            .await?;
        }
    }
    let community = sqlx::query_scalar("SELECT id FROM communities WHERE lower(host) = lower($1)")
        .bind(&authority)
        .fetch_one(&pool)
        .await?;
    let channel = Uuid::new_v4().to_string();
    let mut publisher = BuzzTestClient::connect(&url, &owner).await?;
    accepted(
        &mut publisher,
        sign(
            &owner,
            KIND_NIP29_CREATE_GROUP,
            String::new(),
            vec![
                Tag::parse(["h", &channel])?,
                Tag::parse(["name", &format!("screen-test-{channel}")])?,
                Tag::parse(["visibility", "private"])?,
                Tag::parse(["channel_type", "stream"])?,
                Tag::parse(["ttl", "3600"])?,
            ],
        )?,
    )
    .await?;
    accepted(
        &mut publisher,
        sign(
            &owner,
            KIND_NIP29_PUT_USER,
            String::new(),
            vec![
                Tag::parse(["h", &channel])?,
                Tag::parse(["p", &viewer.public_key().to_hex()])?,
                Tag::parse(["role", "member"])?,
            ],
        )?,
    )
    .await?;
    Ok(Room {
        url,
        other_url,
        channel,
        owner,
        viewer,
        outsider,
        publisher,
        pool,
        community,
    })
}

async fn assert_subscription_closed(client: &mut BuzzTestClient, channel: &str) -> Result<()> {
    client
        .subscribe("forbidden-screen", vec![filter(channel)])
        .await?;
    let message = client.recv_event(DEADLINE).await?;
    assert!(
        matches!(message, RelayMessage::Closed { ref subscription_id, .. }
            if subscription_id == "forbidden-screen"),
        "private screen subscription must be refused: {message:?}"
    );
    Ok(())
}

#[tokio::test]
#[ignore = "Requires Postgres, Redis, and a local relay built from this branch"]
async fn video_delivers_all_timed_frames_and_stop_without_storing_pixels() -> Result<()> {
    let mut room = room().await?;
    let mut viewer = BuzzTestClient::connect(&room.url, &room.viewer).await?;
    viewer
        .subscribe("live-screen", vec![filter(&room.channel)])
        .await?;
    assert!(viewer
        .collect_until_eose("live-screen", DEADLINE)
        .await?
        .is_empty());
    let packets = video_packets()?;
    let mut frames = 0;
    let mut cadence = tokio::time::interval(Duration::from_micros(266_667));
    for packet in packets.iter().take(5) {
        cadence.tick().await;
        let event = screen_event(&room.owner, packet, &[&room.channel])?;
        let id = event.id;
        accepted(&mut room.publisher, event.clone()).await?;
        let received = viewer.recv_event(DEADLINE).await?;
        match received {
            RelayMessage::Event {
                subscription_id,
                event: delivered,
            } => {
                assert_eq!(subscription_id, "live-screen");
                assert_eq!(delivered.id, id);
                assert_eq!(delivered.content, event.content);
                if let ScreenMessage::Video { frames: batch, .. } = packet {
                    frames += batch.len();
                }
            }
            other => bail!("Expected live video, received {other:?}"),
        }
    }
    assert_eq!(frames, 40, "batching must preserve every timed video frame");
    let ScreenMessage::Video { share, .. } = &packets[0] else {
        bail!("Production fixture must contain video");
    };
    let stop = screen_event(
        &room.owner,
        &ScreenMessage::Stopped {
            share: share.clone(),
        },
        &[&room.channel],
    )?;
    let stop_id = stop.id;
    accepted(&mut room.publisher, stop).await?;
    assert!(matches!(
        viewer.recv_event(DEADLINE).await?,
        RelayMessage::Event { event, .. } if event.id == stop_id
    ));
    let mut history = BuzzTestClient::connect(&room.url, &room.viewer).await?;
    history
        .subscribe("screen-history", vec![filter(&room.channel).limit(100)])
        .await?;
    assert!(
        history
            .collect_until_eose("screen-history", DEADLINE)
            .await?
            .is_empty(),
        "screen pixels and stops must never enter event history"
    );
    let stored: i64 = sqlx::query_scalar(
        "SELECT count(*) FROM events WHERE community_id = $1 AND channel_id = $2 AND kind = $3",
    )
    .bind(room.community)
    .bind(Uuid::parse_str(&room.channel)?)
    .bind(KIND_HUDDLE_SCREEN as i32)
    .fetch_one(&room.pool)
    .await?;
    assert_eq!(stored, 0, "ephemeral screen pixels must never be persisted");
    history.disconnect().await?;
    viewer.disconnect().await?;
    room.publisher.disconnect().await?;
    room.pool.close().await;
    Ok(())
}

#[tokio::test]
#[ignore = "Requires Postgres, Redis, and a local relay built from this branch"]
async fn sustained_video_exceeds_chat_quota_without_losing_acknowledgements_or_delivery(
) -> Result<()> {
    let mut room = room().await?;
    let mut viewer = BuzzTestClient::connect(&room.url, &room.viewer).await?;
    viewer
        .subscribe("sustained-screen", vec![filter(&room.channel)])
        .await?;
    assert!(viewer
        .collect_until_eose("sustained-screen", DEADLINE)
        .await?
        .is_empty());
    let packets = video_packets()?;
    let mut cadence = tokio::time::interval(Duration::from_micros(266_667));
    for index in 0..480_usize {
        cadence.tick().await;
        let mut packet = packets[index % packets.len()].clone();
        if let ScreenMessage::Video {
            sequence, frames, ..
        } = &mut packet
        {
            *sequence = index as u64 + 1;
            for frame in frames {
                frame.timestamp += (index / packets.len()) as u64 * 6_000_000;
            }
        }
        let event = screen_event(&room.owner, &packet, &[&room.channel])?;
        let id = event.id;
        accepted(&mut room.publisher, event).await?;
        let received = viewer.recv_event(DEADLINE).await?;
        assert!(
            matches!(received, RelayMessage::Event { event, .. } if event.id == id),
            "batch {index} must be acknowledged and delivered past the chat quota"
        );
    }
    let stored: i64 = sqlx::query_scalar(
        "SELECT count(*) FROM events WHERE community_id = $1 AND channel_id = $2 AND kind = $3",
    )
    .bind(room.community)
    .bind(Uuid::parse_str(&room.channel)?)
    .bind(KIND_HUDDLE_SCREEN as i32)
    .fetch_one(&room.pool)
    .await?;
    assert_eq!(stored, 0);
    viewer.disconnect().await?;
    room.publisher.disconnect().await?;
    room.pool.close().await;
    Ok(())
}

#[tokio::test]
#[ignore = "Requires Postgres, Redis, and a local relay built from this branch"]
async fn screen_access_and_media_guards_bind_the_live_tenant_and_huddle() -> Result<()> {
    let mut room = room().await?;
    let packets = video_packets()?;
    let packet = packets
        .first()
        .context("production video fixture is empty")?;
    let event = screen_event(&room.owner, packet, &[&room.channel])?;
    let mut outsider = BuzzTestClient::connect(&room.url, &room.outsider).await?;
    assert_subscription_closed(&mut outsider, &room.channel).await?;
    assert!(
        !outsider
            .send_event(screen_event(&room.outsider, packet, &[&room.channel])?)
            .await?
            .accepted
    );
    // The same signer is a community owner in both tenants: the host boundary,
    // not identity or a missing relay membership, must protect the screen.
    let mut other_tenant = BuzzTestClient::connect(&room.other_url, &room.owner).await?;
    assert_subscription_closed(&mut other_tenant, &room.channel).await?;
    assert!(!other_tenant.send_event(event.clone()).await?.accepted);
    accepted(&mut room.publisher, event).await?;
    for channels in [vec![], vec![room.channel.as_str(), room.channel.as_str()]] {
        assert!(
            !room
                .publisher
                .send_event(screen_event(&room.owner, packet, &channels)?)
                .await?
                .accepted
        );
    }
    let mut forged = packet.clone();
    if let ScreenMessage::Video { width, .. } = &mut forged {
        *width *= 2;
    }
    assert!(
        !room
            .publisher
            .send_event(screen_event(&room.owner, &forged, &[&room.channel])?)
            .await?
            .accepted,
        "the relay must verify dimensions against actual H.264 SPS bytes"
    );
    accepted(
        &mut room.publisher,
        sign(
            &room.owner,
            KIND_NIP29_EDIT_METADATA,
            String::new(),
            vec![
                Tag::parse(["h", &room.channel])?,
                Tag::parse(["archived", "true"])?,
            ],
        )?,
    )
    .await?;
    assert!(
        !room
            .publisher
            .send_event(screen_event(&room.owner, &packets[1], &[&room.channel])?)
            .await?
            .accepted,
        "an ended huddle cannot continue publishing screen pixels"
    );
    outsider.disconnect().await?;
    other_tenant.disconnect().await?;
    room.publisher.disconnect().await?;
    room.pool.close().await;
    Ok(())
}
