/// Token counts retained from one validated native response.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct AdviserTokenCounts {
    /// Tokens consumed by the native request.
    pub input: u64,
    /// Total tokens generated by the native response.
    pub output: u64,
    /// Generated tokens attributed to hidden reasoning.
    pub reasoning: u64,
}

/// A bounded identity for an already-executed native MCP call. Tool arguments,
/// outputs, and provider response IDs are deliberately absent.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ExecutedToolEvidenceIdentity {
    /// SHA-256 identifier derived from the request-scoped native call identity.
    pub call_id_hash: String,
    /// Catalog-admitted ephemeral MCP server label.
    pub server_label: String,
    /// Exact catalog-admitted tool name.
    pub tool_name: String,
}

/// Validated output plus persistence-safe execution metadata.
#[derive(Clone)]
pub struct AdviserExecutionResult<T> {
    /// Trusted structured output validated against the run ledger.
    pub contribution: T,
    /// Bounded local model instance reported by LM Studio.
    pub model_instance_id: String,
    /// SHA-256 digest of the provider response ID.
    pub response_id_hash: String,
    /// Provider-reported token counts.
    pub token_counts: AdviserTokenCounts,
    /// Identities of validated structured MCP outputs, without their content.
    pub executed_tool_evidence: Vec<ExecutedToolEvidenceIdentity>,
    /// Trusted local start timestamp.
    pub started_at: String,
    /// Trusted local completion timestamp.
    pub finished_at: String,
    /// Bounded metadata-only diagnostics; never prompts, reasoning, or evidence.
    pub diagnostics: Vec<String>,
}

impl<T> fmt::Debug for AdviserExecutionResult<T> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("AdviserExecutionResult")
            .field("contribution", &"[REDACTED]")
            .field("model_instance_id", &self.model_instance_id)
            .field("response_id_hash", &self.response_id_hash)
            .field("token_counts", &self.token_counts)
            .field("executed_tool_evidence", &self.executed_tool_evidence)
            .field("started_at", &self.started_at)
            .field("finished_at", &self.finished_at)
            .field("diagnostics", &self.diagnostics)
            .finish()
    }
}

