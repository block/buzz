/// Stable failure classes suitable for persistence and UI status.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AdviserExecutionErrorCode {
    /// The run cancellation token fired.
    Cancelled,
    /// The trusted caller supplied an invalid bounded request.
    InvalidRequest,
    /// Catalog or native egress policy rejected the request.
    PolicyRejected,
    /// Local LM Studio authentication is unavailable.
    Authentication,
    /// The configured local model is unavailable.
    ModelUnavailable,
    /// The bounded native request timed out.
    Timeout,
    /// The native transport failed or returned a disallowed HTTP response.
    Transport,
    /// Structured tool evidence was not exactly catalog-admitted.
    EvidenceRejected,
    /// The terminal structured output failed its closed Rust contract.
    InvalidOutput,
}

/// A redacted adviser failure. Provider bodies, prompts, evidence, credentials,
/// and response IDs are never retained.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AdviserExecutionError {
    code: AdviserExecutionErrorCode,
    diagnostic: &'static str,
}

impl AdviserExecutionError {
    /// Returns the stable redacted failure class.
    pub const fn code(&self) -> AdviserExecutionErrorCode {
        self.code
    }

    /// Returns a bounded diagnostic containing no model-visible material.
    pub const fn diagnostic(&self) -> &'static str {
        self.diagnostic
    }

    pub(crate) const fn new(code: AdviserExecutionErrorCode, diagnostic: &'static str) -> Self {
        Self { code, diagnostic }
    }
}

pub(crate) const fn cloud_fallback_eligible(code: AdviserExecutionErrorCode) -> bool {
    matches!(
        code,
        AdviserExecutionErrorCode::Authentication
            | AdviserExecutionErrorCode::ModelUnavailable
            | AdviserExecutionErrorCode::Timeout
            | AdviserExecutionErrorCode::Transport
            | AdviserExecutionErrorCode::InvalidOutput
    )
}

impl fmt::Display for AdviserExecutionError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.diagnostic)
    }
}

impl std::error::Error for AdviserExecutionError {}

