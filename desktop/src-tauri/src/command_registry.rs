//! registration that pushed `lib.rs` past the repository's 1000-line file
//! ceiling, and squashing unrelated code to make room would have made the file
//! worse. Extracting the largest cohesive block is the fix `CONTEXT.md` calls
//! for.
//!
//! It is a `macro_rules!` and not a function because `tauri::generate_handler!`
