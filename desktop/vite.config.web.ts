// Web/PWA build of the shared desktop React app. Tauri APIs are aliased to browser shims in src/platform/web.
import fs from "node:fs";
import path from "node:path";
import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { tanstackRouter } from "@tanstack/router-plugin/vite";

const shim = (f: string) => path.resolve(__dirname, "src/platform/web", f);
const protectedOn = process.env.VITE_BUZZ_BESTIE === "1";

let outDirResolved: string | undefined;
// One id per build: baked into the bundle and written to /version.json so open apps can tell a newer build is live.
const BUILD_ID = process.env.VITE_BUZZ_WEB_BUILD_ID || `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;

export default defineConfig(({ command }) => ({
  plugins: [
    tanstackRouter({
      target: "react",
      routesDirectory: "./src/app/routes",
      generatedRouteTree: "./src/app/routeTree.gen.ts",
      virtualRouteConfig: "./src/app/routes.ts",
      quoteStyle: "double",
      semicolons: true,
      routeTreeFileHeader: [
        "// biome-ignore-all lint: generated by TanStack Router",
      ],
    }),
    react(),
    {
      name: "buzz-web-html",
      configureServer(server) {
        // DEV-only same-origin proxy for cross-origin relays: /__relay/<encoded http(s) base>/<path> (POST /query, /events).
        // Also GET/HEAD /media/<sha>.<ext> (auth-gated images) and PUT /upload | /media/upload (attachments).
        server.middlewares.use(async (req, res, next) => {
          const m = req.url?.match(
            /^\/__relay\/([^/]+)(\/(?:query|events|upload|media\/upload|media\/[\da-f]{64}(?:\.thumb)?\.[a-z0-9]{2,5}|workflows\/[\da-f-]{36}\/runs(?:\/[\da-f-]{36}\/approvals)?))(\?.*)?$/i,
          );
          const method = req.method ?? "";
          const allowed = m
            ? m[2] === "/query" || m[2] === "/events"
              ? method === "POST"
              : /upload$/.test(m[2])
                ? method === "PUT"
                : method === "GET" || method === "HEAD"
            : false;
          if (!m || !allowed) return next();
          try {
            const base = decodeURIComponent(m[1]);
            if (!/^https?:\/\/[^/]+$/.test(base)) throw new Error("bad relay base");
            const hasBody = method === "POST" || method === "PUT";
            const chunks: Buffer[] = [];
            if (hasBody) for await (const c of req) chunks.push(c as Buffer);
            const headers: Record<string, string> = {};
            for (const h of ["content-type", "authorization", "x-sha-256", "range"])
              if (req.headers[h]) headers[h] = String(req.headers[h]);
            if (hasBody && !headers["content-type"])
              headers["content-type"] = "application/json";
            const r = await fetch(base + m[2] + (m[3] ?? ""), {
              method,
              headers,
              body: hasBody ? Buffer.concat(chunks) : undefined,
            });
            res.statusCode = r.status;
            res.setHeader("content-type", r.headers.get("content-type") ?? "application/json");
            for (const h of ["content-range", "accept-ranges", "cache-control", "etag"]) {
              const v = r.headers.get(h);
              if (v) res.setHeader(h, v);
            }
            res.end(method === "HEAD" ? undefined : Buffer.from(await r.arrayBuffer()));
          } catch (e) {
            res.statusCode = 502;
            res.end(JSON.stringify({ error: `dev proxy: ${e instanceof Error ? e.message : e}` }));
          }
        });
        server.middlewares.use((req, _res, next) => {
          if (req.url === "/" || req.url?.startsWith("/?"))
            req.url = "/index.web.html" + (req.url.slice(1) || "");
          next();
        });
      },
      configResolved(c) {
        outDirResolved = path.resolve(c.root, c.build.outDir);
      },
      closeBundle() {
        const out = outDirResolved ?? path.resolve(__dirname, "dist-web");
        if (fs.existsSync(path.join(out, "index.web.html")))
          fs.renameSync(
            path.join(out, "index.web.html"),
            path.join(out, "index.html"),
          );
        if (fs.existsSync(out))
          fs.writeFileSync(path.join(out, "version.json"), JSON.stringify({ build: BUILD_ID }) + "\n");
      },
    },
  ],
  define: {
    "import.meta.env.VITE_BUZZ_PLATFORM": JSON.stringify("web"),
    // dev server: no build id → the update check stays off (tests set it through VITE_BUZZ_WEB_BUILD_ID)
    "import.meta.env.VITE_BUZZ_WEB_BUILD_ID": JSON.stringify(command === "build" || process.env.VITE_BUZZ_WEB_BUILD_ID ? BUILD_ID : ""),
    // Default relay: prod builds → wss://buzz.huladesk.com; dev server → ws://localhost:3000. Override with VITE_BUZZ_RELAY_URL.
    "import.meta.env.VITE_BUZZ_RELAY_URL": JSON.stringify(
      process.env.VITE_BUZZ_RELAY_URL ||
        (command === "build"
          ? "wss://buzz.huladesk.com"
          : "ws://localhost:3000"),
    ),
  },
  resolve: {
    alias: [
      { find: /^@tauri-apps\/api\/core$/, replacement: shim("core.ts") },
      { find: /^@tauri-apps\/api\/event$/, replacement: shim("event.ts") },
      {
        find: /^@tauri-apps\/api\/(window|webview|webviewWindow|app|path)$/,
        replacement: shim("misc.ts"),
      },
      { find: /^@tauri-apps\/api\/mocks$/, replacement: shim("misc.ts") },
      {
        find: /^@tauri-apps\/plugin-(notification|opener|process|updater)$/,
        replacement: shim("misc.ts"),
      },
      {
        find: /^@features-manifest$/,
        replacement: path.resolve(__dirname, "../preview-features.json"),
      },
      {
        find: /^@protected-features$/,
        replacement: path.resolve(
          __dirname,
          protectedOn
            ? "./src/protectedFeatures/internal.ts"
            : "./src/protectedFeatures/public.ts",
        ),
      },
      {
        find: /^@protected-feature-components$/,
        replacement: path.resolve(
          __dirname,
          protectedOn
            ? "./src/protectedFeatures/internalUi.ts"
            : "./src/protectedFeatures/publicUi.ts",
        ),
      },
      {
        find: /^@model-capabilities-manifest$/,
        replacement: path.resolve(
          __dirname,
          "../scripts/model-capabilities.json",
        ),
      },
      { find: /^@\//, replacement: "/src/" },
    ],
  },
  server: {
    port: parseInt(process.env.VITE_PORT || "5199", 10),
    strictPort: true,
    host: process.env.VITE_HOST || "127.0.0.1",
    allowedHosts: [".ts.net", "localhost", "127.0.0.1"],
    fs: {
      allow: [
        __dirname,
        "..",
        path.resolve(fs.realpathSync("node_modules"), "../.."),
      ],
    },
  },
  build: {
    outDir: "dist-web",
    emptyOutDir: true,
    target: "es2022",
    rollupOptions: { input: path.resolve(__dirname, "index.web.html") },
  },
}));
